"""Build the position-independent ARM zlib used by the guest streaming API.

Pass the Debian upstream source archive zlib_1.3.dfsg+really1.3.1.orig.tar.gz.
Requires Clang, LLD and llvm-nm (release build: LLVM 19.1.7).
"""
import argparse
import base64
import hashlib
import json
import struct
import subprocess
import tarfile
import tempfile
from pathlib import Path

DIGEST = "60dd315c07f616887caa029408308a018ace66e3d142726a97db164b3b8f69fb"
SOURCES = "inflate inffast inftrees adler32 crc32 deflate trees zutil".split()
EXPORTS = "inflateInit2_ inflate inflateEnd deflateInit2_ deflate deflateEnd".split()
DEST = Path(__file__).resolve().parents[1] / "web/vendor"

def build(archive, dest):
    if hashlib.sha256(archive.read_bytes()).hexdigest() != DIGEST:
        raise SystemExit("Unexpected zlib source digest")
    with tarfile.open(archive) as tar:
        tar.extractall(dest, filter="data")
    source = dest / "zlib-1.3.1"
    flags = ["--target=armv7-none-eabi", "-march=armv7-a", "-marm", "-mfloat-abi=soft",
             "-DZ_SOLO", "-ffreestanding", "-fPIC", "-fvisibility=hidden", "-fno-stack-protector",
             "-fno-unwind-tables", "-fno-asynchronous-unwind-tables", "-ffunction-sections",
             "-fdata-sections", "-O2", "-c"]
    objects = []
    for name in SOURCES:
        obj = dest / (name + ".o")
        subprocess.run(["clang", *flags, source / (name + ".c"), "-o", obj], check=True)
        objects.append(obj)
    elf = dest / "zlib.so"
    subprocess.run(["ld.lld", "-shared", "--gc-sections", "-Bsymbolic", "--no-undefined", "--hash-style=sysv",
                    "-z", "max-page-size=4096", *(arg for fn in EXPORTS for arg in ("-u", fn)),
                    "-o", elf, *objects], check=True)
    blob = elf.read_bytes()
    assert blob[:6] == b"\x7fELF\x01\x01"
    phoff, shoff = struct.unpack_from("<II", blob, 28)
    phsize, phnum, shsize, shnum = struct.unpack_from("<4H", blob, 42)
    image = bytearray()
    segments = []
    for i in range(phnum):
        kind, offset, addr, _, size, memsz, flags, _ = struct.unpack_from("<8I", blob, phoff + i * phsize)
        if kind != 1:
            continue
        end = (addr + memsz + 4095) & ~4095
        image.extend(bytes(max(0, end - len(image))))
        image[addr:addr + size] = blob[offset:offset + size]
        # ELF PF_X/PF_W/PF_R -> Unicorn READ/WRITE/EXEC
        perms = (1 if flags & 4 else 0) | (2 if flags & 2 else 0) | (4 if flags & 1 else 0)
        assert perms in (1, 3, 5)
        segments.append([addr & ~4095, end - (addr & ~4095), perms])
    relocations = []
    for i in range(shnum):
        _, kind, _, _, off, size, *_ = struct.unpack_from("<10I", blob, shoff+i*shsize)
        if kind != 9:
            continue
        for pos in range(off, off+size, 8):
            location, info = struct.unpack_from("<2I", blob, pos)
            assert info == 23 and location % 4 == 0 and location + 4 <= len(image)
            assert struct.unpack_from("<I", image, location)[0] < len(image)
            relocations.append(location)
    symbols = subprocess.check_output(["llvm-nm", "--defined-only", elf], text=True)
    entries = {}
    for row in symbols.splitlines():
        addr, kind, name = row.split()
        if name in EXPORTS:
            assert kind in ("T","t")
            entries[name] = int(addr,16)
    assert set(entries) == set(EXPORTS)
    output = ["// Generated by scripts/build-guest-zlib.py from zlib 1.3.1. See zlib-LICENSE.txt.",
              "export const segments = " + json.dumps(segments) + ";",
              "export const relocations = " + json.dumps(relocations) + ";",
              "export const entries = " + json.dumps(entries) + ";",
              'export const base64 = "' + base64.b64encode(image).decode("ascii") + '";']
    (DEST / "zlib-arm.mjs").write_text("\n".join(output)+"\n")
    (DEST / "zlib-LICENSE.txt").write_bytes((source / "LICENSE").read_bytes())

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as temp:
        build(args.archive, Path(temp))
