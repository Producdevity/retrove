test("Darwin random matches native libc sequences for zero, signed and unsigned boundary seeds", () => {
  for (const { seed, expected } of vectors) {
    const random = new DarwinRandom(seed);
    expect(Array.from({ length: expected.length }, () => random.next())).toEqual(expected);
  }
});
test("srandom restarts a per-runtime sequence without sharing state between guests", () => {
  const first = randomImports(),
    second = randomImports();
  const call = (seed: number) => first._srandom(() => seed);
  const expected = Array.from({ length: 100 }, () => second._random());
  expect(Array.from({ length: 100 }, () => first._random())).toEqual(expected);
  call(2);
  expect(first._random()).toBe(1505335290);
  call(1);
  expect(Array.from({ length: 100 }, () => first._random())).toEqual(expected);
});
